from kit import *
IMC, TXC = "#0F766E", "#B45309"                    # image side (teal), text side (amber)
TILES = [("he_tumor.png", "tumor"), ("he_mucosa.png", "normal mucosa"), ("he_adipose.png", "adipose tissue"), ("he_lymphocytes.png", "lymphocytes")]
SIM = [[0.32, 0.18, 0.05, 0.12], [0.20, 0.30, 0.06, 0.10], [0.04, 0.07, 0.34, 0.03], [0.14, 0.11, 0.02, 0.29]]   # illustrative cosines
P0 = [0.82, 0.11, 0.02, 0.05]                      # softmax of row 1 divided by 0.07
def tile(name, h):
    return ImageMobject(he_image(name, 240)).set_height(h)
def capbox(s, size=22):
    """A caption in quotes inside an amber box that fits the text."""
    t = T(f"“{s}”", size, TXC)
    r = RoundedRectangle(corner_radius=0.1, width=t.width + 0.4, height=0.55, stroke_color=TXC, stroke_width=2, fill_color="#FEF3C7", fill_opacity=1)
    return VGroup(r, t.move_to(r))
class C1(Clip):
    TITLE = "CLIP: matching images with their captions"
    PACE, HOLD = 1.1, 0.4
    def construct(self):
        # 1. from two views to image + caption
        self.cap("CLIP pairs an image with its caption, instead of two views of one image.", hold=0)
        hl = T("Week 6: contrastive learning", 24, GREY, BOLD).move_to([-3.6, 2.5, 0])
        f = ecg_fn(4, hr=75, seed=11)
        v1 = wave(f, 0.2, 2.6, 3.4, 0.6, color=OC).shift([-5.3, 1.1, 0])
        v2 = wave(lambda t: 0.65 * f(t) + 0.2 * np.sin(2 * np.pi * 0.35 * t), 0.2, 2.6, 3.4, 0.6, color=OC).shift([-5.3, -1.0, 0])
        l1, l2 = T("view 1", 20, OC, BOLD).next_to(v1, UP, buff=0.15).align_to(v1, LEFT), T("view 2", 20, OC, BOLD).next_to(v2, UP, buff=0.15).align_to(v2, LEFT)
        m1 = DoubleArrow([-3.6, 0.85, 0], [-3.6, -0.15, 0], buff=0, stroke_width=3, color=GREY, tip_length=0.18)
        hr = T("CLIP", 24, UF, BOLD).move_to([3.4, 2.5, 0])
        im = tile("he_tumor.png", 1.9).move_to([3.4, 1.0, 0])
        cb = capbox("colorectal adenocarcinoma, H&E").move_to([3.4, -1.3, 0])
        m2 = DoubleArrow(im.get_bottom() + DOWN * 0.08, cb.get_top() + UP * 0.08, buff=0, stroke_width=3, color=INK, tip_length=0.18)
        il, tl = T("image", 20, IMC, BOLD).next_to(im, LEFT, buff=0.25), T("caption", 20, TXC, BOLD).next_to(cb, DOWN, buff=0.15)
        cr = T(HE_CREDIT, 20, GREY).move_to([0, -2.55, 0])
        dv = DashedLine([0, 2.6, 0], [0, -2.1, 0], color=GREY, stroke_width=2)
        self.play(FadeIn(hl), Create(v1), Create(v2), FadeIn(l1), FadeIn(l2), GrowFromCenter(m1), run_time=1.2)
        self.play(Create(dv), FadeIn(hr), FadeIn(im), FadeIn(il), FadeIn(cr), run_time=0.8)
        self.play(GrowFromCenter(m2), FadeIn(cb), FadeIn(tl), run_time=0.8)
        self.rest(2.8)
        # 2. two encoders, one space
        self.cap("An image encoder and a text encoder map both into one shared embedding space.", hold=0)
        self.play(*[FadeOut(m) for m in (hl, v1, v2, l1, l2, m1, hr, m2, il, tl, dv)], im.animate.set_height(1.6).move_to([-4.4, 1.2, 0]), cb.animate.scale(0.9).move_to([-4.4, -1.3, 0]), run_time=0.8)
        ie = box("Image encoder\n(vision transformer)", 2.9, 1.1, "#CCFBF1", size=22, stroke=IMC).move_to([0.25, 1.2, 0])
        te = box("Text encoder\n(transformer)", 2.9, 1.1, "#FEF3C7", size=22, stroke=TXC).move_to([0.25, -1.3, 0])
        a1 = Arrow(im.get_right(), ie.get_left(), buff=0.12, stroke_width=3.5, color=INK, max_tip_length_to_length_ratio=0.25)
        a2 = Arrow(cb.get_right(), te.get_left(), buff=0.12, stroke_width=3.5, color=INK, max_tip_length_to_length_ratio=0.25)
        sp = Circle(radius=1.5, color=GREY, stroke_width=2).move_to([4.9, 0.0, 0])
        spl = T("shared embedding space", 20, GREY).next_to(sp, UP, buff=0.15)
        di = Dot([4.45, 0.45, 0], radius=0.14, color=IMC).set_z_index(3)
        dt = Dot([5.05, 0.15, 0], radius=0.14, color=TXC).set_z_index(3)
        b1 = Arrow(ie.get_right(), di.get_center(), buff=0.18, stroke_width=3.5, color=IMC, max_tip_length_to_length_ratio=0.12)
        b2 = Arrow(te.get_right(), dt.get_center(), buff=0.18, stroke_width=3.5, color=TXC, max_tip_length_to_length_ratio=0.12)
        nl = T("each: 512 numbers, length 1", 20, GREY).next_to(sp, DOWN, buff=0.2)
        self.play(GrowArrow(a1), FadeIn(ie), GrowArrow(a2), FadeIn(te), run_time=0.9)
        self.play(Create(sp), FadeIn(spl), GrowArrow(b1), GrowArrow(b2), FadeIn(di, scale=0.5), FadeIn(dt, scale=0.5), run_time=1.0)
        self.play(FadeIn(nl), run_time=0.4)
        self.rest(2.8)
        # 3. a batch of four pairs: 4 x 4 similarities
        self.cap("A batch of four pairs gives a 4 × 4 grid of similarities; the matching pairs lie on the diagonal.", hold=0)
        self.play(*[FadeOut(m) for m in (im, cb, ie, te, a1, a2, sp, spl, di, dt, b1, b2, nl)], run_time=0.6)
        cell, gx, gy = 1.05, -3.0, 0.92                      # cell size, center of the top-left cell
        cc = lambda i, j: np.array([gx + j * cell, gy - i * cell, 0])
        R = Group(*[tile(n, 0.85).move_to(cc(i, 0) + LEFT * 1.4) for i, (n, _) in enumerate(TILES)])
        C = VGroup(*[T(lab, 20, TXC, BOLD) for _, lab in TILES])
        for j, c in enumerate(C):
            c.rotate(PI / 4).move_to(cc(0, j) + UP * (cell / 2 + 0.1) + LEFT * 0.15, aligned_edge=DL)
        rl = T("tiles", 22, IMC, BOLD).next_to(R, LEFT, buff=0.2)
        cl = T("captions", 22, TXC, BOLD).move_to([2.3, gy + 1.45, 0])
        cells = VGroup(*[Square(cell, stroke_color=WHITE, stroke_width=3, fill_color=PC, fill_opacity=0.1 + 2.3 * SIM[i][j]).move_to(cc(i, j)) for i in range(4) for j in range(4)])
        nums = VGroup(*[T(f"{SIM[i][j]:.2f}", 22, WHITE if SIM[i][j] > 0.25 else INK, BOLD if i == j else NORMAL).move_to(cc(i, j)) for i in range(4) for j in range(4)])
        diag = VGroup(*[Square(cell - 0.06, stroke_color=INK, stroke_width=4).move_to(cc(i, i)) for i in range(4)])
        sl = VGroup(T("each cell: cosine similarity", 20, GREY), T("of a tile and a caption", 20, GREY)).arrange(DOWN, aligned_edge=LEFT, buff=0.06).move_to([1.4, -1.9, 0], aligned_edge=LEFT)
        self.play(LaggedStart(*[FadeIn(r) for r in R], lag_ratio=0.15), FadeIn(rl), LaggedStart(*[FadeIn(c) for c in C], lag_ratio=0.15), FadeIn(cl), cr.animate.move_to([4.4, -2.65, 0]), run_time=1.0)
        self.play(FadeIn(cells), FadeIn(nums), FadeIn(sl), run_time=0.9)
        self.play(LaggedStart(*[Create(d) for d in diag], lag_ratio=0.2), run_time=0.9)
        self.rest(2.8)
        # 4. row softmax
        self.cap("Each row becomes a softmax: the tumor tile gives its own caption 0.82.", hold=0)
        rb = SurroundingRectangle(VGroup(*cells[0:4]), color=IMC, buff=0.04, stroke_width=4)
        ra = Arrow(cc(0, 3) + RIGHT * 0.6, [2.15, gy, 0], buff=0, stroke_width=3.5, color=INK, max_tip_length_to_length_ratio=0.2)
        rt = VGroup(T("÷ τ (0.07)", 20, INK), T("softmax", 20, INK)).arrange(DOWN, buff=0.06).next_to(ra, DOWN, buff=0.12)
        bars = VGroup(*[Rectangle(width=2.0 * p + 0.02, height=0.34, stroke_width=0, fill_color=IMC if j == 0 else "#9CA3AF", fill_opacity=1).move_to([4.35, gy - 0.5 * j, 0], aligned_edge=LEFT) for j, p in enumerate(P0)])
        bl = VGroup(*[T(lab, 20, TXC).next_to(np.array([4.2, b.get_center()[1], 0]), LEFT, buff=0) for b, (_, lab) in zip(bars, TILES)])
        bn = VGroup(*[T(f"{p:.2f}", 20, INK, BOLD if j == 0 else NORMAL).next_to(b, RIGHT, buff=0.1) for j, (p, b) in enumerate(zip(P0, bars))])
        pl = T("tumor tile: which caption?", 20, IMC, BOLD).move_to([4.5, gy + 0.65, 0])
        self.play(Create(rb), run_time=0.5)
        self.play(GrowArrow(ra), FadeIn(rt), FadeIn(pl), run_time=0.6)
        self.play(LaggedStart(*[AnimationGroup(GrowFromEdge(b, LEFT), FadeIn(l), FadeIn(n)) for b, l, n in zip(bars, bl, bn)], lag_ratio=0.15), run_time=1.1)
        self.rest(3.0)
        # 5. rows and columns
        self.cap("The loss is cross-entropy along every row and every column, averaged.", hold=0)
        self.play(FadeOut(VGroup(rb, ra, rt, bars, bl, bn, pl, sl)), run_time=0.5)
        ha = SurroundingRectangle(VGroup(*cells[4:8]), color=IMC, buff=0.04, stroke_width=5)
        va = SurroundingRectangle(VGroup(*cells[1::4]), color=TXC, buff=0.04, stroke_width=5)
        t1 = VGroup(T("rows: image → text", 22, IMC, BOLD), T("each tile picks its caption", 20, GREY)).arrange(DOWN, aligned_edge=LEFT, buff=0.08).move_to([1.4, 1.1, 0], aligned_edge=LEFT)
        t2 = VGroup(T("columns: text → image", 22, TXC, BOLD), T("each caption picks its tile", 20, GREY)).arrange(DOWN, aligned_edge=LEFT, buff=0.08).next_to(t1, DOWN, buff=0.4).align_to(t1, LEFT)
        t3 = T("loss = average of the two = 0.18", 22, INK, BOLD).next_to(t2, DOWN, buff=0.5).align_to(t1, LEFT)
        self.play(Create(ha), FadeIn(t1), run_time=0.9)
        self.play(Create(va), FadeIn(t2), run_time=0.9)
        self.play(FadeIn(t3), run_time=0.5)
        self.rest(3.0)
        # 6. scale
        self.cap("CLIP trained on 400 million image–text pairs from the web, with batches of 32,768.", hold=0)
        self.play(FadeOut(Group(R, C, rl, cl, cells, nums, diag, ha, va, t1, t2, t3, cr)), run_time=0.6)
        cards = [("400 million", "image–text pairs from the web"), ("32,768", "pairs per batch: a 32,768 × 32,768 grid"), ("0.07", "starting temperature, then learned")]
        K = VGroup(*[VGroup(T(a, 40, UF, BOLD), T(b, 22, INK)).arrange(DOWN, buff=0.2) for a, b in cards]).arrange(DOWN, buff=0.55).move_to([0, 0.35, 0])
        src = T("Radford et al., ICML 2021", 20, GREY).move_to([0, -2.6, 0])
        self.play(LaggedStart(*[FadeIn(k, shift=UP * 0.15) for k in K], lag_ratio=0.35), FadeIn(src), run_time=1.6)
        self.rest(3.0)
        # 7. BiomedCLIP
        self.cap("BiomedCLIP uses the same recipe on 15 million figure–caption pairs from PubMed Central.", hold=0)
        self.play(FadeOut(K), FadeOut(src), run_time=0.5)
        fig = Rectangle(width=4.4, height=3.6, stroke_color=GREY, stroke_width=2, fill_color="#F8FAFC", fill_opacity=1).move_to([-3.4, 0.35, 0])
        fi = tile("he_tumor.png", 1.9).move_to([-3.4, 1.0, 0])
        ft = VGroup(T("Figure 2. H&E section showing", 20, INK), T("moderately differentiated", 20, INK), T("colorectal adenocarcinoma.", 20, INK)).arrange(DOWN, aligned_edge=LEFT, buff=0.06).next_to(fi, DOWN, buff=0.2)
        fl = T("one figure and its caption (illustrative)", 20, GREY).next_to(fig, DOWN, buff=0.15)
        st = VGroup(T("15 million", 40, UF, BOLD), T("figure–caption pairs", 22, INK), T("from 4.4 million articles", 22, INK), T("Zhang et al., BiomedCLIP", 20, GREY)).arrange(DOWN, buff=0.18).move_to([3.3, 0.5, 0])
        st[3].shift(DOWN * 0.25)
        cr.move_to([0, -2.55, 0])
        self.play(FadeIn(fig), FadeIn(fi), FadeIn(ft), FadeIn(fl), FadeIn(cr), run_time=0.9)
        self.play(FadeIn(st, shift=UP * 0.15), run_time=0.8)
        self.rest(3.2)
