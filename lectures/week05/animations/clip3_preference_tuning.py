from kit import *
CH, RJ = "#0F766E", "#B45309"                      # chosen answer (teal), rejected answer (amber)
def answer(label, text, color):
    """A labeled answer box."""
    t = T(text, 24, INK)
    r = RoundedRectangle(corner_radius=0.1, width=t.width + 0.5, height=0.7, stroke_color=color, stroke_width=3, fill_color=WHITE, fill_opacity=1)
    l = T(label, 22, color, BOLD)
    return VGroup(l, VGroup(r, t.move_to(r))).arrange(RIGHT, buff=0.3)
def gain_bar(v, color, x, unit=0.26, y0=-0.6):
    """A vertical bar from the zero line, v units up (positive) or down (negative)."""
    h = max(abs(v) * unit, 0.02)
    r = Rectangle(width=0.9, height=h, stroke_width=0, fill_color=color, fill_opacity=1)
    return r.move_to([x, y0, 0], aligned_edge=DOWN if v >= 0 else UP)
class C3(Clip):
    TITLE = "Preference tuning: RLHF and DPO"
    PACE, HOLD = 1.2, 0.5
    def construct(self):
        # 1. a preference pair
        self.cap("Preference data pairs one question with a chosen and a rejected answer.", hold=0)
        q = VGroup(T("Note: The patient denies chest pain.", 24, INK), T("Question: Does the patient report chest pain?", 24, INK)).arrange(DOWN, aligned_edge=LEFT, buff=0.14)
        qb = SurroundingRectangle(q, color=GREY, buff=0.2, corner_radius=0.1, fill_color="#E2E8F0", fill_opacity=1, stroke_width=2)
        Q = VGroup(qb, q).move_to([0, 1.9, 0])
        c = answer("chosen", "No. The note says the patient denies chest pain.", CH)
        r = answer("rejected", "Yes, the patient reports chest pain.", RJ)
        VGroup(c, r).arrange(DOWN, aligned_edge=LEFT, buff=0.35).move_to([0, 0.0, 0])
        who = T("a clinician picked the chosen answer", 22, GREY).next_to(r, DOWN, buff=0.4).align_to(r, LEFT)
        self.play(FadeIn(Q, shift=DOWN * 0.15), run_time=0.7)
        self.play(FadeIn(c, shift=RIGHT * 0.15), run_time=0.7)
        self.play(FadeIn(r, shift=RIGHT * 0.15), run_time=0.7)
        self.play(FadeIn(who), run_time=0.5)
        self.rest(2.4)
        # 2. what the model prefers now
        self.cap("Right now, Qwen3-0.6B rates the wrong answer as far more likely.", hold=0)
        self.play(FadeOut(who), run_time=0.3)
        lc = T("log-probability −21.37", 24, CH, BOLD).next_to(c, RIGHT, buff=0.3)
        lr = T("log-probability −1.12", 24, RJ, BOLD).next_to(r, RIGHT, buff=0.3)
        grp = VGroup(c, r, lc, lr)
        if grp.width > 13.4: grp.scale_to_fit_width(13.4)
        grp.move_to([0, 0.0, 0])
        self.play(FadeIn(lc), run_time=0.6)
        self.play(FadeIn(lr), run_time=0.6)
        hi = T("higher (closer to 0) means more likely; real values for the post-trained model", 20, GREY).move_to([0, -1.5, 0])
        self.play(FadeIn(hi), run_time=0.5)
        self.rest(2.4)
        # 3. RLHF
        self.cap("RLHF trains a reward model on such choices, then reinforcement learning follows it.", hold=0)
        self.play(*[FadeOut(m) for m in (Q, grp, hi)], run_time=0.5)
        st = [("preference\npairs", "#E2E8F0"), ("reward model\nscores answers", "#FEF3C7"), ("reinforcement\nlearning (PPO)", "#DBEAFE"), ("updated\nLLM", "#DBEAFE")]
        P = VGroup(*[box(s, 2.75, 1.2, f, 22) for s, f in st]).arrange(RIGHT, buff=0.55).move_to([0, 0.6, 0])
        PA = VGroup(*[Arrow(a.get_right(), b.get_left(), buff=0.05, stroke_width=3, color=GREY, max_tip_length_to_length_ratio=0.3) for a, b in zip(P, P[1:])])
        nt = T("two models to train, and reinforcement learning can be unstable", 22, GREY).next_to(P, DOWN, buff=0.6)
        self.play(LaggedStart(*[FadeIn(p, shift=RIGHT * 0.15) for p in P], lag_ratio=0.35), LaggedStart(*[GrowArrow(a) for a in PA], lag_ratio=0.35), run_time=2.0)
        self.play(FadeIn(nt), run_time=0.5)
        self.rest(2.4)
        # 4. DPO: no reward model; compare with a frozen copy
        self.cap("DPO skips the reward model and compares the model with a frozen copy of itself.", hold=0)
        self.play(P[1].animate.set_opacity(0.25), PA[0].animate.set_opacity(0.25), PA[1].animate.set_opacity(0.25), FadeOut(nt), run_time=0.6)
        self.play(*[FadeOut(m) for m in (P, PA)], run_time=0.4)
        m1 = box("model being trained", 4.0, 0.8, "#DBEAFE", 24).move_to([-3.4, 1.6, 0])
        m2 = box("frozen copy (reference)", 4.0, 0.8, "#E5E7EB", 24).move_to([3.4, 1.6, 0])
        g = T("gain = log-probability under the model − log-probability under the frozen copy", 22, INK).move_to([0, 0.35, 0])
        k = T("the frozen copy keeps the model close to what it already knew", 22, GREY).move_to([0, -0.35, 0])
        self.play(FadeIn(m1), FadeIn(m2), run_time=0.7)
        self.play(FadeIn(g, shift=UP * 0.1), run_time=0.7)
        self.play(FadeIn(k), run_time=0.5)
        self.rest(2.4)
        # 5. the DPO loss
        self.cap("The DPO loss gets smaller as the chosen gain pulls ahead of the rejected gain.", hold=0)
        self.play(FadeOut(k), FadeOut(m1), FadeOut(m2), g.animate.move_to([0, 2.2, 0]).set_color(GREY), run_time=0.6)
        f = VGroup(T("loss = −log σ( β × (", 28, INK), T("chosen gain", 28, CH, BOLD), T("−", 28, INK), T("rejected gain", 28, RJ, BOLD), T(") )", 28, INK)).arrange(RIGHT, buff=0.12).move_to([0, 1.4, 0])
        bt = T("σ is the sigmoid; β = 0.1 sets how strongly the gap counts", 22, GREY).next_to(f, DOWN, buff=0.25)
        self.play(FadeIn(f, shift=UP * 0.1), run_time=0.8)
        self.play(FadeIn(bt), run_time=0.5)
        self.rest(2.4)
        # 6. at the start: both gains 0
        self.cap("At the start, both gains are zero, so the loss is 0.69.", hold=0)
        self.play(FadeOut(bt), FadeOut(g), run_time=0.4)
        zl = Line([-6.0, -0.6, 0], [-0.6, -0.6, 0], stroke_color=GREY, stroke_width=2)
        zt = T("0", 20, GREY).next_to(zl, LEFT, buff=0.15)
        bc, br = gain_bar(0, CH, -4.4), gain_bar(0, RJ, -2.2)
        lbc = T("chosen gain", 20, CH, BOLD).move_to([-4.4, -2.55, 0]); lbr = T("rejected gain", 20, RJ, BOLD).move_to([-2.2, -2.55, 0])
        vc = T("0", 24, CH, BOLD).next_to(bc, UP, buff=0.15); vr = T("0", 24, RJ, BOLD).next_to(br, UP, buff=0.15)
        calc = VGroup(T("β × (0 − 0) = 0", 26, INK), T("σ(0) = 0.5", 26, INK), T("loss = −log 0.5 = 0.69", 26, INK, BOLD)).arrange(DOWN, aligned_edge=LEFT, buff=0.3).move_to([0.6, -0.6, 0], aligned_edge=LEFT)
        self.play(Create(zl), FadeIn(zt), FadeIn(bc), FadeIn(br), FadeIn(lbc), FadeIn(lbr), FadeIn(vc), FadeIn(vr), run_time=0.8)
        self.play(LaggedStart(*[FadeIn(l, shift=UP * 0.1) for l in calc], lag_ratio=0.35), run_time=1.4)
        self.rest(2.4)
        # 7. after training: +4 and -6
        self.cap("After training, the gains are +4 and −6, and the loss falls to 0.31.", hold=0)
        bc2, br2 = gain_bar(4, CH, -4.4), gain_bar(-6, RJ, -2.2)
        vc2 = T("+4", 24, CH, BOLD).next_to(bc2, UP, buff=0.12); vr2 = T("−6", 24, RJ, BOLD).next_to(br2, RIGHT, buff=0.15)
        calc2 = VGroup(T("β × (4 − (−6)) = 0.1 × 10 = 1.0", 26, INK), T("σ(1.0) = 0.73", 26, INK), T("loss = −log 0.73 = 0.31", 26, INK, BOLD)).arrange(DOWN, aligned_edge=LEFT, buff=0.3).move_to(calc, aligned_edge=UL)
        self.play(Transform(bc, bc2), Transform(br, br2), Transform(vc, vc2), Transform(vr, vr2), run_time=1.4)
        self.play(FadeOut(calc), run_time=0.3)
        self.play(LaggedStart(*[FadeIn(l, shift=UP * 0.1) for l in calc2], lag_ratio=0.35), run_time=1.4)
        self.rest(2.6)
