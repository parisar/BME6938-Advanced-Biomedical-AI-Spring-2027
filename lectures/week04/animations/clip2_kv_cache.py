from kit import *
CACHE = "#7C3AED"                                  # KV cache outline (purple)
def kv_pair(seed):
    return VGroup(mat(3, 1, KC, cell=0.3, seed=seed), mat(3, 1, VC, cell=0.3, seed=seed + 50)).arrange(RIGHT, buff=0.06)
def bar(width, color, label, value, y):
    r = Rectangle(width=max(width, 0.06), height=0.45, stroke_width=0, fill_color=color, fill_opacity=1).move_to([-6.0, y, 0], aligned_edge=LEFT)
    lab = T(label, 22, INK).next_to(r, UP, buff=0.12).align_to(r, LEFT)
    val = T(value, 24, INK, BOLD).next_to(r, RIGHT, buff=0.2)
    return VGroup(r, lab, val)
class C2(Clip):
    TITLE = "The KV cache and how models shrink it"
    PACE, HOLD = 1.2, 0.5
    def construct(self):
        # 1. a new token needs the keys and values of all earlier tokens
        self.cap("Each new token needs the keys and values of every earlier token.", hold=0)
        words = ["The", "patient", "denies", "chest", "pain"]; xs = [-5.0 + 1.75 * i for i in range(6)]
        W = VGroup(*[tok(w, INK, w=1.5, h=0.55, size=22).move_to([x, 2.3, 0]) for w, x in zip(words, xs)])
        nq = tok("?", INK, w=1.5, h=0.55, size=24, fill="#FEF3C7").move_to([xs[5], 2.3, 0])
        KV = VGroup(*[kv_pair(10 + i).move_to([x, 1.0, 0]) for i, x in enumerate(xs[:5])])
        q = mat(3, 1, QC, cell=0.3, seed=99).move_to([xs[5], 1.0, 0])
        lab = VGroup(T("keys", 20, KC, BOLD), T("values", 20, VC, BOLD)).arrange(RIGHT, buff=0.3).next_to(KV[0], DOWN, buff=0.25)
        ql = T("query", 20, QC, BOLD).next_to(q, DOWN, buff=0.25)
        self.play(LaggedStart(*[FadeIn(w) for w in W], lag_ratio=0.1), FadeIn(nq), run_time=1.0)
        self.play(LaggedStart(*[FadeIn(p, shift=DOWN * 0.15) for p in KV], lag_ratio=0.1), FadeIn(lab), run_time=1.0)
        self.play(FadeIn(q), FadeIn(ql), run_time=0.5)
        lines = VGroup(*[SurroundingRectangle(p, color=AMB, buff=0.07, stroke_width=4) for p in KV])
        cmp = T("the query is compared with every earlier key", 22, GREY).move_to([0, -0.35, 0])
        self.play(LaggedStart(*[Create(l) for l in lines], lag_ratio=0.2), FadeIn(cmp), run_time=1.2)
        self.rest(2.2)
        # 2. store them: the KV cache
        self.cap("The model stores them instead of recomputing them: the KV cache.", hold=0)
        self.play(FadeOut(lines), FadeOut(cmp), run_time=0.4)
        cb = DashedVMobject(SurroundingRectangle(KV, color=CACHE, buff=0.18, stroke_width=4), num_dashes=60)
        cl = T("KV cache", 24, CACHE, BOLD).next_to(cb, DOWN, buff=0.55).align_to(cb, LEFT)
        self.play(Create(cb), FadeIn(cl), run_time=0.9)
        self.wait(0.6)
        nw = tok("and", INK, w=1.5, h=0.55, size=22).move_to(nq)
        nkv = kv_pair(40).move_to([xs[5], 1.0, 0])
        self.play(FadeTransform(nq, nw), FadeOut(q), FadeOut(ql), run_time=0.7)
        self.play(FadeIn(nkv, shift=DOWN * 0.15), run_time=0.6)
        cb2 = DashedVMobject(SurroundingRectangle(VGroup(KV, nkv), color=CACHE, buff=0.18, stroke_width=4), num_dashes=72)
        self.play(Transform(cb, cb2), FadeIn(T("each new token adds its keys and values", 22, GREY).next_to(cl, RIGHT, buff=0.4)), run_time=0.9)
        self.rest(2.2)
        # 3. how big it gets
        self.cap("The cache grows with every token, in every layer and every head.", hold=0)
        self.play(*[FadeOut(m) for m in self.mobjects if m not in (self.title, self._cap)], run_time=0.6)
        f1 = T("per token:  2 (keys and values) × 32 layers × 32 heads × 128 numbers × 2 bytes", 24, INK).move_to([0, 2.3, 0])
        f2 = T("= 0.5 MB per token", 26, INK, BOLD).next_to(f1, DOWN, buff=0.3)
        f3 = T("model shaped like Llama 3 8B, 16-bit numbers", 20, GREY).next_to(f2, DOWN, buff=0.2)
        self.play(FadeIn(f1), run_time=0.8)
        self.play(FadeIn(f2), FadeIn(f3), run_time=0.6)
        B1 = bar(9.0, "#9CA3AF", "a 32,768-token patient record, every head with its own keys and values", "16 GB", -0.6)
        self.play(GrowFromEdge(B1[0], LEFT), FadeIn(B1[1]), run_time=1.0)
        self.play(FadeIn(B1[2]), run_time=0.4)
        self.rest(2.4)
        # 4. grouped-query attention
        self.cap("Grouped-query attention: 8 key/value heads instead of 32, a 4× smaller cache.", hold=0)
        B2 = bar(2.25, KC, "grouped-query attention: 8 key/value heads", "4 GB", -1.85)
        qh = VGroup(*[Square(0.13, stroke_width=0, fill_color=QC, fill_opacity=0.85) for _ in range(32)]).arrange(RIGHT, buff=0.04).move_to([3.4, -1.3, 0])
        kv = VGroup(*[Square(0.13, stroke_width=0, fill_color=KC, fill_opacity=0.85) for _ in range(8)])
        for g in range(8): kv[g].move_to([qh[4 * g: 4 * g + 4].get_x(), -2.05, 0])
        lk = VGroup(*[Line(qh[i].get_bottom(), kv[i // 4].get_top(), stroke_width=1.5, color=GREY) for i in range(32)])
        qt = T("32 query heads", 20, QC, BOLD).next_to(qh, UP, buff=0.12)
        kt = T("8 key/value heads", 20, KC, BOLD).move_to([qh.get_x(), -2.4, 0])
        self.play(FadeIn(qh), FadeIn(qt), run_time=0.5)
        self.play(Create(lk), FadeIn(kv), FadeIn(kt), run_time=0.9)
        self.play(GrowFromEdge(B2[0], LEFT), FadeIn(B2[1]), FadeIn(B2[2]), run_time=1.0)
        self.rest(2.4)
        # 5. multi-head latent attention
        self.cap("Latent attention (DeepSeek-V3) caches one small compressed vector per token.", hold=0)
        self.play(*[FadeOut(m) for m in self.mobjects if m not in (self.title, self._cap)], run_time=0.6)
        h = T("DeepSeek-V3, per token and per layer", 24, INK, BOLD).move_to([0, 2.45, 0])
        M1 = bar(9.0, "#9CA3AF", "full keys and values for 128 heads", "40,960 numbers", 1.1)
        M2 = bar(9.0 * 576 / 40960, CACHE, "latent attention: a compressed vector (512) plus a RoPE key (64)", "576 numbers", -0.25)
        r71 = T("about 71× smaller", 28, CACHE, BOLD).move_to([0, -1.45, 0])
        ex = T("keys and values are rebuilt from the latent vector when they are needed", 22, GREY).next_to(r71, DOWN, buff=0.25)
        self.play(FadeIn(h), GrowFromEdge(M1[0], LEFT), FadeIn(M1[1]), FadeIn(M1[2]), run_time=1.0)
        self.play(GrowFromEdge(M2[0], LEFT), FadeIn(M2[1]), FadeIn(M2[2]), run_time=1.0)
        self.play(FadeIn(r71), run_time=0.5)
        self.play(FadeIn(ex), run_time=0.5)
        self.rest(2.4)
        # 6. sliding-window attention
        self.cap("Sliding-window attention: most layers look only at the most recent tokens.", hold=0)
        self.play(*[FadeOut(m) for m in self.mobjects if m not in (self.title, self._cap)], run_time=0.6)
        n = 24; sx = [-6.0 + 0.36 * i for i in range(n)]
        def row(y, lo, label, sub):
            sq = VGroup(*[Square(0.28, stroke_color=WHITE, stroke_width=1, fill_color=(AMB if i == n - 1 else (CACHE if i >= lo else "#E5E7EB")), fill_opacity=(1 if i >= lo else 1)).move_to([x, y, 0]) for i, x in enumerate(sx)])
            return VGroup(sq, T(label, 22, INK, BOLD).next_to(sq, UP, buff=0.15).align_to(sq, LEFT), T(sub, 20, GREY).next_to(sq, RIGHT, buff=0.3))
        G = row(1.6, 0, "global layer", "sees every earlier token")
        Lw = row(0.0, n - 8, "local layer", "sees a window of recent tokens")
        lg = VGroup(VGroup(Square(0.25, stroke_width=0, fill_color=AMB, fill_opacity=1), T("current token", 20, INK)).arrange(RIGHT, buff=0.15),
                    VGroup(Square(0.25, stroke_width=0, fill_color=CACHE, fill_opacity=1), T("tokens it attends to", 20, INK)).arrange(RIGHT, buff=0.15)).arrange(RIGHT, buff=0.6).move_to([-2.0, -1.1, 0])
        gm = VGroup(T("Gemma 3, the base of MedGemma:", 22, INK, BOLD), T("5 local layers with a 1,024-token window for every global layer", 22, INK)).arrange(DOWN, buff=0.15).move_to([0, -2.25, 0])
        self.play(FadeIn(G), run_time=0.8)
        self.play(FadeIn(Lw), FadeIn(lg), run_time=0.8)
        self.play(FadeIn(gm), run_time=0.6)
        self.rest(2.6)
